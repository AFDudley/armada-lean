# Call sites


TOKEN_RE = re.compile(r"[\w'!?₀-₉]+(?:\.[\w'!?₀-₉]+)*")


def parse_named_arg(text: str, i: int, j: int) -> tuple[str, int, int] | None:
    """`text[i:j]` is a `(...)`-delimited group. `(name := expr)` → `(name,
    value_start, value_end)`, the value span trimmed of surrounding
    whitespace; `None` for any other parenthesized group."""
    vs0, ve0 = i + 1, j - 1
    m = re.match(r"\s*([\w'!?₀-₉]+)\s*:=\s*", text[vs0:ve0])
    if not m:
        return None
    vs = vs0 + m.end()
    ve = ve0
    while ve > vs and text[ve - 1] in " \t\n":
        ve -= 1
    return m.group(1), vs, ve


def locate_call_args(text: str, mask: list[bool], start: int, explicit_names: list[str],
                      targets: set[str]) -> dict[str, tuple[int, int, int, int]]:
    """Walk the application arguments of a call starting at `start` (right
    after the callee), matching each one against `explicit_names` (the
    callee's own EXPLICIT parameters, in order, from its ORIGINAL —
    pre-conversion — header): a named argument `(name := expr)` fills `name`
    wherever it appears; an unlabeled argument fills the first unfilled name
    of `explicit_names`, in order. Stops once every name of `targets` has a
    span. Returns name → (value_start, value_end, full_start, full_end): the
    value span is the argument's own expression (no `name :=` wrapper, no
    parens of a named argument); the full span also covers that wrapper, for
    a clean deletion."""
    i = start
    found: dict[str, tuple[int, int, int, int]] = {}
    filled: set[str] = set()
    next_idx = 0
    n = len(explicit_names)
    while not targets <= found.keys():
        i = skip_ws(text, mask, i)
        if i >= len(text) or not mask[i]:
            raise ConvertError(f"ran out of arguments before {sorted(targets - found.keys())}")
        if text[i] == "@":
            raise ConvertError("a fully-explicit (`@`) call is not supported")
        if text[i] in OPEN:
            j = match_close(text, mask, i)
            named = parse_named_arg(text, i, j) if text[i] == "(" else None
            if named:
                name, vs, ve = named
                span = (vs, ve, i, j)
            else:
                if next_idx >= n:
                    raise ConvertError("more positional arguments than explicit parameters")
                name = explicit_names[next_idx]
                span = (i, j, i, j)
            filled.add(name)
            i = j
        else:
            m = TOKEN_RE.match(text, i)
            if not m:
                raise ConvertError(f"cannot parse an argument at {i}")
            if next_idx >= n:
                raise ConvertError("more positional arguments than explicit parameters")
            name = explicit_names[next_idx]
            span = (i, m.end(), i, m.end())
            filled.add(name)
            i = m.end()
        if name in targets:
            found[name] = span
        while next_idx < n and explicit_names[next_idx] in filled:
            next_idx += 1
    return found


def delete_edit(s: int, e: int, text: str) -> tuple[int, int, str]:
    """Delete `text[s:e]`, eating one run of horizontal whitespace right
    before it so the deletion leaves no double space."""
    while s > 0 and text[s - 1] in " \t":
        s -= 1
    return s, e, ""


def pair_call_edits(text: str, spans: dict[str, tuple[int, int, int, int]],
                     p: Pair, state_explicit: bool, proof_expr: str) -> list[tuple[int, int, str]]:
    """The edits that replace one `(state, hyp)` pair's call-site arguments
    with the one `ReachableState` value its converted binder now takes,
    `⟨state, proof⟩` (or `⟨_, proof⟩` when the state binder was implicit, so
    the call never gave it explicitly): whichever of the two arguments comes
    first in the text is deleted outright; the other's own span (its
    `name :=` wrapper too, if it had one) is replaced by the combined value,
    always given positionally — the parameter it fills has a new name."""
    hvs, hve, hfs, hfe = spans[p.hyp]
    hyp_text = proof_expr.format(hyp=text[hvs:hve])
    if not state_explicit:
        return [(hfs, hfe, f"⟨_, {hyp_text}⟩")]
    svs, sve, sfs, sfe = spans[p.state]
    combined = f"⟨{text[svs:sve]}, {hyp_text}⟩"
    if sfs < hfs:
        return [delete_edit(sfs, sfe, text), (hfs, hfe, combined)]
    return [delete_edit(hfs, hfe, text), (sfs, sfe, combined)]


def rename_calls(texts: dict[str, str], c: "Conversion", iffs: list[dict]) -> dict[str, str]:
    """Rewrite every use of the converted theorem `c`: its old state and
    reachability-hypothesis arguments become the one `ReachableState` value
    its new header takes, built at the call site (`⟨s, h⟩`, or `⟨_, h⟩` when
    the state binder was implicit). No compatibility helper, no renamed
    call: `foo` still calls `foo`. Returns the changed texts and records
    each site in `c.calls`."""
    full = c.theorem["name"]
    comps = full.split(".")
    suffixes = {".".join(comps[k:]) for k in range(len(comps))}
    short = comps[-1]
    explicit_names = [n for g in c.header.groups if g.bracket == "(" for n in g.names]
    pairs_info = []
    for p in c.pairs:
        sg = next(g for g in c.header.groups if p.state in g.names)
        hyp_ty = next(g.type_text for g in c.header.groups if p.hyp in g.names)
        native = reach_type(hyp_ty, p.state, p.head)[1] is not None
        proof_expr = f"({iff_to_machine(iffs, p.head)} {{hyp}})" if native else "{hyp}"
        pairs_info.append((p, sg.bracket == "(", proof_expr))
    targets = {p.hyp for p, _, _ in pairs_info} | {p.state for p, se, _ in pairs_info if se}
    tok = re.compile(r"(?<![\w'!?.])@?[\w.'!?₀-₉]*" + re.escape(short) + r"(?![\w'!?.])")
    out = {}
    for path, text in texts.items():
        if short not in text:
            continue
        mask = code_mask(text)
        edits: list[tuple[int, int, str]] = []
        for m in tok.finditer(text):
            name = m.group(0)
            if not mask[m.start()] or name.lstrip("@") not in suffixes:
                continue
            line_start = text.rfind("\n", 0, m.start()) + 1
            before = text[line_start : m.start()]
            if re.match(r"^(?:@\[[^\]]*\]\s*)?(?:private |protected )?theorem\s+$", before):
                continue  # the declaration itself
            if name.startswith("@"):
                raise ConvertError(f"{path}: a fully-explicit (`@`) call of {full} is not supported")
            spans = locate_call_args(text, mask, m.end(), explicit_names, targets)
            for p, state_explicit, proof_expr in pairs_info:
                edits += pair_call_edits(text, spans, p, state_explicit, proof_expr)
            c.calls.append((path, text.count("\n", 0, m.start()) + 1))
        if edits:
            out[path] = apply_edits(text, edits)
    return out


