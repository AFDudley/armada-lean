#!/usr/bin/env python3
"""Convert a tree to the spec-module form. Design record: `docs/spec-module-design.md`.

Usage: python3 scripts/convert_spec.py [--root DIR]

Run from the repo root of any branch whose tree builds: the trunk at cutover, or an
in-flight worker branch (operator decision 2026-10-31, decision 3: rolling cutover).
The script is deterministic and idempotent: a second run on a converted tree changes
nothing.

Steps:
1. `lake build`, then `scripts/spec_report.lean` (the computed facts).
2. Spec membership (`spec_lib.citations`, decision 1).
3. Reachability as a type (decision 2). For a spec theorem with a state binder
   `(s : S)` and a hypothesis `(h : R … s)`, where `R` is `Machine.Reachable` or a
   predicate with a proved iff to it, the two binders become one binder
   `(s : ReachableState M)` (or `Nitro.ReachableNetwork`, `Nitro.ReachableParticipant`).
   The header writes the state as `s.state`. The proof body gets one generated access
   line, `obtain_reach ⟨s, h⟩ := s` (term form `obtain_reach% …;`), unless the body is
   `sorry`. A call of a converted theorem passes `⟨s, h⟩` (or `⟨_, h⟩`) for the two old
   arguments. The script prints every such site.
4. `ArmadaLean/Spec/<module>.lean`: one `def … Spec.x : Prop` per spec theorem, with
   the theorem's doc comment. An entry over a raw state type and no reachable state
   gets the line "Every state: REASON" (from the existing spec file, then from
   `scripts/reach-exempt.tsv`, then a generated reason for a proved theorem).
   `#check_spec_bindings` ends each file.
5. `ArmadaLean/Witness/<module>.lean`: one `….witness : spec_premise% …` per spec
   entry with a hypothesis. An existing witness is kept. A new one is proved by
   `spec_witness` from the tagged example of `ArmadaLean/Nitro/NonVacuity.lean` (the
   example becomes `theorem <tag>.nonvacuity`, header only), or it is open (`sorry`).
6. The aggregators `ArmadaLean/Spec.lean`, `ArmadaLean/Witness.lean`, and their imports
   in `ArmadaLean.lean`.
"""
