def apply_edits(text: str, edits: list[tuple[int, int, str]]) -> str:
    for s, e, r in sorted(edits, key=lambda x: (x[0], x[1]), reverse=True):
        text = text[:s] + r + text[e:]
    return text


def add_imports(text: str, modules: list[str]) -> str:
    lines = text.split("\n")
    last = max((k for k, ln in enumerate(lines) if ln.startswith("import ")), default=-1)
    present = {ln.strip() for ln in lines if ln.startswith("import ")}
    new = [f"import {m}" for m in modules if f"import {m}" not in present]
    if not new:
        return text
    lines[last + 1 : last + 1] = new
    return "\n".join(lines)


def nonvacuity_examples(text: str, members: set[str]) -> dict[str, list[tuple[int, int, str]]]:
    """Spec theorem short name → [(start, end, keyword text)] of its examples in
    `NonVacuity.lean`. An example belongs to the theorem that its own doc comment
    names first (a doc comment that starts with the name in backticks). An example with no doc comment of its own
    belongs to the nearest earlier doc comment that names a spec theorem: the file
    puts shared values between that comment and the example."""
    out: dict[str, list[tuple[int, int, str]]] = {}
    tag_re = re.compile(r"^/--\s*`([^`]+)`", re.M)
    for m in re.finditer(r"^(example|theorem (\S+)\.nonvacuity(?:_\d+)?)(?=\s|:)", text, re.M):
        prev = text[: m.start()].rstrip("\n")
        tag = None
        if prev.endswith("-/"):
            tm = re.match(r"/--\s*`([^`]+)`", prev[prev.rfind("/--"):])
            if tm and tm.group(1) in members:
                tag = tm.group(1)
        if tag is None:
            for tm in reversed(list(tag_re.finditer(text, 0, m.start()))):
                if tm.group(1) in members:
                    tag = tm.group(1)
                    break
        if tag is not None:
            out.setdefault(tag, []).append((m.start(), m.end(), m.group(0)))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    root = Path(args.root).resolve()

    build = subprocess.run([spec_lib.LAKE, "build"], cwd=root, capture_output=True, text=True)
    if build.returncode != 0:
        print(build.stdout[-3000:], build.stderr[-3000:], file=sys.stderr)
        print("convert_spec: the tree does not build; fix it first", file=sys.stderr)
        return 1
    report = spec_lib.run_report(root)
    theorems = spec_lib.source_theorems(root, report)
    members, _ = spec_lib.classify(theorems)
    by_file: dict[str, list[dict]] = {}
    for t in members:
        by_file.setdefault(t["path"], []).append(t)
    exempt = read_exempt(root)

    texts = {p: (root / p).read_text(encoding="utf-8") for p in by_file}
    conversions: list[Conversion] = []
    errors: list[str] = []
    plans: list[tuple[str, dict, list[Pair]]] = []
    for path in sorted(by_file):
        text = texts[path]
        mask = code_mask(text)
        for t in sorted(by_file[path], key=lambda x: x["line"]):
            bs = t["binders"]
            pairs = [Pair(bs[b["reach_of"]]["name"], b["name"], b["head"])
                     for b in bs if b["reach_of"] is not None]
            try:
                hd = parse_header(text, mask, theorem_index(text, t["line"]))
                if pairs:
                    convert_header(text, hd, pairs)  # fails early on a bad shape
                    c = Conversion(t, hd, pairs)
                    conversions.append(c)
            except ConvertError as e:
                errors.append(f"{path}:{t['line']} {t['name']}: {e}")
                continue
            plans.append((path, t, pairs))
    if errors:
        print("convert_spec: cannot convert:", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        return 1

    # Call sites first, on the unconverted text: they may lie in converted bodies.
    # Call sites: a use of a converted theorem keeps calling the same theorem,
    # with its two old arguments replaced by the one `ReachableState` value.
    files = sorted(p for p in (root / "ArmadaLean").rglob("*.lean")
                   if p.relative_to(root).parts[1] not in ("Spec", "Witness"))
    all_texts = {str(p.relative_to(root)): p.read_text(encoding="utf-8") for p in files}
    changed: dict[str, str] = {}
    for c in conversions:
        for path, new_text in rename_calls(all_texts, c, report["reach_iffs"]).items():
            all_texts[path] = changed[path] = new_text

    # Headers and bodies, on the text after the call-site edits.
    spec_members: dict[str, list] = {}
    reasons: dict[str, str | None] = {}
    needs: dict[str, bool] = {}
    old_reasons: dict[str, dict[str, str]] = {}
    for path, t, pairs in plans:
        text = changed.get(path) or texts[path]
        mask = code_mask(text)
        kw = find_theorem(text, t)
        hd = parse_header(text, mask, kw)
        new_header = text[hd.kw : hd.assign]
        if pairs:
            new_header, access = convert_header(text, hd, pairs)
            body = text[hd.assign + 2 : hd.body_end]
            new_body = repair_body(body, access).rstrip("\n") + "\n\n"
            text = text[: hd.kw] + new_header + ":=" + new_body + text[hd.body_end :]
            changed[path] = text
        ntext = new_header + ":= sorry"
        nhd = parse_header(ntext, code_mask(ntext), 0)
        binders = (ntext[nhd.groups[0].start : nhd.colon].rstrip() if nhd.groups else "")
        conclusion = nhd.type_text(ntext).strip()
        params = autobound(texts[path], parse_header(texts[path], code_mask(texts[path]),
                                                      theorem_index(texts[path], t["line"])), t["binders"])
        spec_members.setdefault(path, []).append((t, new_header, binders, conclusion, params))
        bs = t["binders"]
        converted = {p.hyp for p in pairs}
        raw = any(b["state"] for b in bs)
        reach = bool(pairs) or any(b["reach_sub"] for b in bs)
        sfull = spec_name(t["name"])
        if raw and not reach:
            if path not in old_reasons:
                old_reasons[path] = existing_every_state(root / spec_rel(path))
            decl = hd.name
            r = old_reasons[path].get(spec_name(decl))
            r = r or lookup_exempt(exempt, t["name"])
            if not r and "sorryAx" not in t["axioms"]:
                r = GENERATED_REASON
            if r and not r.endswith("."):
                r += "."
            reasons[t["name"]] = r
            if not r:
                errors.append(f"{path}:{t['line']} {t['name']}: raw state, no reachability, "
                              "no reason, open proof: needs a reviewed reason added to "
                              "scripts/reach-exempt.tsv")
        hi, hj = header_slice(parse_header(texts[path], code_mask(texts[path]),
                                           theorem_index(texts[path], t["line"])), bs)
        needs[sfull] = any(b["prop"] and b["name"] not in converted for b in bs[:hj])
    if errors:
        print("convert_spec: cannot convert:", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        return 1
    machine_module = {m["name"]: m["module"] for m in report["machines"]}
    for path in changed:
        mods = []
        if any(c.theorem["path"] == path for c in conversions):
            mods = ["ArmadaLean.Types.Reachable", "ArmadaLean.SpecTools"]
        for c in conversions:
            if c.theorem["path"] != path:
                continue
            for p in c.pairs:
                hyp_ty = next(g.type_text for g in c.header.groups if p.hyp in g.names)
                mods.append(machine_module[machine_of(reach_type(hyp_ty, p.state, p.head)[0])])
        mods = [m for m in dict.fromkeys(mods) if m != rel_module(path)]
        if mods:
            changed[path] = add_imports(changed[path], mods)

    # Non-vacuity examples that become named witnesses' sources.
    nv_path = root / NONVACUITY
    nv_text = changed.get(NONVACUITY) or (nv_path.read_text(encoding="utf-8") if nv_path.exists() else "")
    nv_names: dict[str, str] = {}
    if nv_text:
        tags = nonvacuity_examples(nv_text, {t["name"].split(".")[-1] for t in members})
        renames = []
        for t in members:
            short = t["name"].split(".")[-1]
            spec_full = spec_name(t["name"])
            if not needs.get(spec_full) or short not in tags:
                continue
            for k, (s, e, cur) in enumerate(tags[short]):
                nm = f"{short}.nonvacuity" + ("" if k == 0 else f"_{k + 1}")
                if cur != f"theorem {nm}":
                    renames.append((s, e, f"theorem {nm}"))
            nv_names[spec_full] = f"{NONVACUITY_MODULE}.{short}.nonvacuity"
        nv_text = apply_edits(nv_text, renames)
        changed[NONVACUITY] = nv_text

    for path, new in changed.items():
        write_lean(root / path, new)

    # Spec files.
    spec_files, witness_files = [], []
    for path in sorted(spec_members):
        text = changed.get(path) or (root / path).read_text(encoding="utf-8")
        # Re-parse positions in the converted text.
        mask = code_mask(text)
        rows = []
        for t, new_header, binders, conclusion, params in spec_members[path]:
            hd = parse_header(text, mask, find_theorem(text, t))
            rows.append((t, hd, new_header, binders, conclusion, params))
        module = rel_module(path)
        out = build_spec_file(path, text, rows, module, reasons)
        sp = root / spec_rel(path)
        sp.parent.mkdir(parents=True, exist_ok=True)
        write_lean(sp, out)
        spec_files.append(rel_module(spec_rel(path)))

        # Witness file.
        wneeds = []
        for t, *_ in rows:
            if needs.get(spec_name(t["name"])):
                wneeds.append(spec_name(t["name"]))
        wp = root / witness_rel(path)
        if not wneeds:
            if wp.exists():
                wp.unlink()
            continue
        old_blocks: dict[str, str] = {}
        old_imports: list[str] = []
        old_opens: list[str] = []
        if wp.exists():
            wtext = wp.read_text(encoding="utf-8")
            for m in re.finditer(r"(/--.*?-/\s*)?theorem (\S+)\.witness\b.*?(?=\n/--|\ntheorem |\Z)",
                                 wtext, re.S):
                old_blocks[m.group(2)] = m.group(0).rstrip() + "\n"
            # A kept witness can need the fixtures its author imported and opened
            # (`Witness/CircuitValues.lean`, `PoolNonVacuity.lean`): keep the file's own
            # `import` lines, and the `open` lines before its first declaration.
            preamble = re.split(r"\n(?=/--|theorem )", wtext, maxsplit=1)[0]
            old_imports = re.findall(r"^import (\S+)", preamble, re.M)
            old_opens = re.findall(r"^open .*$", preamble, re.M)
        blocks = []
        imports = [rel_module(spec_rel(path)), "ArmadaLean.SpecTools", *old_imports]
        for sf in wneeds:
            if sf in old_blocks:
                blocks.append(old_blocks[sf])
                if "spec_witness " + NONVACUITY_MODULE in old_blocks[sf]:
                    imports.append(NONVACUITY_MODULE)
                continue
            if sf in nv_names:
                blocks.append(
                    f"/-- The witness of `{sf}`, from `{nv_names[sf]}`. -/\n"
                    f"theorem {sf}.witness : spec_premise% {sf} := by\n"
                    f"  spec_witness {nv_names[sf]}\n")
                imports.append(NONVACUITY_MODULE)
            else:
                blocks.append(
                    f"/-- The witness of `{sf}`: open. -/\n"
                    f"theorem {sf}.witness : spec_premise% {sf} := by\n"
                    f"  sorry\n")
        imports = sorted(set(imports))
        wout = (WITNESS_HEADER.format(path=path) + "".join(f"import {m}\n" for m in imports)
                + "".join(f"\n{o}" for o in old_opens) + ("\n" if old_opens else "")
                + "\n" + "\n".join(blocks))
        wp.parent.mkdir(parents=True, exist_ok=True)
        write_lean(wp, wout)
        witness_files.append(rel_module(witness_rel(path)))

    # Aggregators.
    write_lean(root / "ArmadaLean/Spec.lean",
        "/-\n  All spec statement modules (`docs/spec-module-design.md`). Generated by\n"
        "  `scripts/convert_spec.py`.\n-/\n" + "".join(f"import {m}\n" for m in sorted(spec_files)))
    write_lean(root / "ArmadaLean/Witness.lean",
        "/-\n  All non-vacuity witness modules (`docs/spec-module-design.md`). Generated by\n"
        "  `scripts/convert_spec.py`.\n-/\n" + "".join(f"import {m}\n" for m in sorted(witness_files)))
    rootf = root / "ArmadaLean.lean"
    rt = rootf.read_text(encoding="utf-8")
    for m in ("ArmadaLean.Spec", "ArmadaLean.Witness"):
        if f"import {m}\n" not in rt:
            rt = rt.rstrip("\n") + f"\nimport {m}\n"
    write_lean(rootf, rt)

    # Report the access repairs.
    print(f"convert_spec: {len(members)} spec theorems, {len(conversions)} converted")
    for c in conversions:
        body = texts[c.theorem["path"]][c.header.assign + 2 : c.header.body_end]
        tag = "sorry body, no access line" if is_sorry_body(body) else "access line"
        print(f"CONVERTED {c.theorem['path']}:{c.theorem['line']} {c.theorem['name']} ({tag})")
        for path, line in c.calls:
            print(f"CALLSITE {path}:{line} {c.theorem['name']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
