SCOPE = re.compile(r"^(namespace\b|end\b|section\b|noncomputable section\b|open\b(?!.*\bin\s*$)|"
                   r"variable\b|universe\b)")
PREFIX_IN = re.compile(r"^(omit\b|open\b|set_option\b|include\b).*\bin\s*$")


def doc_block(text: str, kw: int) -> tuple[int, str, list[str]]:
    """(start of the declaration's leading block, doc comment text, `… in` prefix lines)."""
    line_start = text.rfind("\n", 0, kw) + 1
    lines = text[:line_start].split("\n")[:-1]
    k = len(lines)
    doc_lines: list[str] = []
    prefix: list[str] = []
    # attributes / modifiers on their own line
    while k > 0 and re.match(r"^@\[.*\]\s*$", lines[k - 1]):
        k -= 1
    if k > 0 and lines[k - 1].rstrip().endswith("-/"):
        j = k - 1
        while j >= 0 and not lines[j].lstrip().startswith("/--"):
            j -= 1
        if j >= 0:
            doc_lines = lines[j:k]
            k = j
    while k > 0 and PREFIX_IN.match(lines[k - 1]):
        prefix.insert(0, lines[k - 1])
        k -= 1
    start = sum(len(ln) + 1 for ln in lines[:k])
    return start, "\n".join(doc_lines), prefix


def spec_def_text(declname: str, doc: str, prefix: list[str], binders: str,
                  conclusion: str, every_state: str | None, params: list[str]) -> str:
    """One spec definition. `binders` and `conclusion` keep their source layout."""
    comps = declname.split(".")
    spec_name = ".".join(comps[:-1] + ["Spec", comps[-1]])
    if every_state:
        if not doc:
            doc = "/-- -/"
        inner = doc[len("/--"):].rstrip()
        assert inner.endswith("-/")
        inner = inner[:-2].rstrip()
        doc = "/--" + inner + "\n\n    Every state: " + every_state + " -/"
    out = list(prefix)
    if doc:
        out.append(doc)
    out.append(f"def {' '.join([spec_name] + params)} : Prop :=")
    if binders:
        out.append("  ∀ " + binders + ",")
    out.append("    Claim <|")
    out.append("    " + conclusion)
    return "\n".join(out) + "\n"


def existing_every_state(path: Path) -> dict[str, str]:
    """`Spec` name → its "Every state:" reason, read from an existing spec file."""
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r"/--(.*?)-/\s*def (\S+)[^\n]*: Prop", text, re.S):
        r = spec_lib.every_state_reason(m.group(1))
        if r:
            out[m.group(2)] = " ".join(r.split())
    return out


def read_exempt(root: Path) -> dict[str, str]:
    path = root / REACH_EXEMPT
    if not path.exists():
        return {}
    out = {}
    for line in path.read_text(encoding="utf-8").split("\n"):
        if not line.strip() or line.startswith("#"):
            continue
        name, reason = line.split("\t", 1)
        out[name] = reason.strip()
    return out


def lookup_exempt(exempt: dict[str, str], full: str) -> str | None:
    for k, v in exempt.items():
        if full == k or full.endswith("." + k):
            return v
    return None


def build_spec_file(src_path: str, text: str, members: list[tuple[dict, Header, str, list[str], str]],
                    module: str, reasons: dict[str, str | None]) -> str:
    """The spec file for one source file. `members`: (theorem, header, header text
    after conversion, binders, conclusion), in source order."""
    mask = code_mask(text)
    # Scope commands at column 0, in code, with their positions.
    scope: list[tuple[int, str]] = []
    pos = 0
    lines = text.split("\n")
    for ln in lines:
        if ln and mask[pos] and SCOPE.match(ln):
            scope.append((pos, ln))
        pos += len(ln) + 1
    items: list[tuple[int, str]] = list(scope)
    for t, hd, _, binders, conclusion, params in members:
        start, doc, prefix = doc_block(text, hd.kw)
        items.append((start, spec_def_text(hd.name, doc, prefix, binders, conclusion,
                                           reasons.get(t["name"]), params)))
    items.sort(key=lambda x: x[0])
    out = [SPEC_HEADER.format(path=src_path), f"import {module}", "import ArmadaLean.SpecTools", "",
           "open ArmadaLean.SpecTools (Claim)", ""]
    for _, s in items:
        if s.endswith("\n"):
            out.append(s)
        else:
            out.append(s + "\n")
    out.append("#check_spec_bindings\n")
    body = "\n".join(out)
    body = re.sub(r"\n{3,}", "\n\n", body)
    return body


def spec_rel(src_rel: str) -> str:
    return "ArmadaLean/Spec/" + src_rel[len("ArmadaLean/"):]


def witness_rel(src_rel: str) -> str:
    return "ArmadaLean/Witness/" + src_rel[len("ArmadaLean/"):]


def rel_module(rel: str) -> str:
    return rel[: -len(".lean")].replace("/", ".")


def write_lean(path: Path, text: str) -> None:
    """Write `text` to `path`, with exactly one trailing newline. A converted
    theorem's body separator (`repair_body`) leaves a blank line for the
    declaration that follows it; at the end of a file no declaration follows,
    so that same separator becomes a stray blank line. Normalizing here, at
    every write, keeps `check.sh`'s `pre-commit` (`end-of-file-fixer`) a
    no-op on this script's own output."""
    path.write_text(text.rstrip("\n") + "\n", encoding="utf-8")


def iff_to_machine(iffs: list[dict], head: str) -> str:
    """`I.mpr` or `I.mp`: the proved iff `I` (`scripts/spec_report.lean`,
    `reach_iffs`) read in the direction native predicate → `Machine.Reachable`."""
    for i in iffs:
        if i["lhs"] == "Machine.Reachable" and i["rhs"] == head:
            return i["name"] + ".mpr"
        if i["rhs"] == "Machine.Reachable" and i["lhs"] == head:
            return i["name"] + ".mp"
    raise ConvertError(f"no proved iff between {head} and Machine.Reachable")


def machine_of(ty: str) -> str:
    """The machine constant that a reachable-state type text names."""
    m = re.match(r"Nitro\.Reachable(Network|Participant)\b", ty)
    if m:
        return "Nitro.network" if m.group(1) == "Network" else "Nitro.participant"
    m = re.match(r"ReachableState \(?([\w.]+)", ty)
    if not m:
        raise ConvertError(f"no machine in {ty!r}")
    return m.group(1)


def header_slice(hd: Header, binders: list[dict]) -> tuple[int, int]:
    """The Lean binders (`binders`, the full telescope of the theorem type) that the
    header binder groups declare: indices [i, j). Before i: section variables and
    auto-bound implicits. From j: the binders of the conclusion."""
    hnames: list[str | None] = []
    for g in hd.groups:
        hnames += g.names if g.names else [None]
    lnames = [b["name"] for b in binders]
    for i in range(len(lnames) - len(hnames) + 1):
        if all(h is None or h == ln for h, ln in zip(hnames, lnames[i:])):
            return i, i + len(hnames)
    raise ConvertError("cannot match the header binders to the Lean binders")


def autobound(text: str, hd: Header, binders: list[dict]) -> list[str]:
    """The auto-bound implicit binders of a theorem (`autoImplicit`): Lean binders
    before the header binders that no `variable` command declares. A spec
    definition states them as explicit parameters, `{x : T}`."""
    hnames: list[str | None] = []
    for g in hd.groups:
        hnames += g.names if g.names else [None]
    lnames = [b["name"] for b in binders]
    for i in range(len(lnames) - len(hnames) + 1):
        if all(h is None or h == ln for h, ln in zip(hnames, lnames[i:])):
            break
    else:
        raise ConvertError("cannot match the header binders to the Lean binders")
    declared: set[str] = set()
    mask = code_mask(text)
    for m in re.finditer(r"^variable\b(.*)$", text[: hd.kw], re.M):
        if not mask[m.start()]:
            continue
        for g in re.finditer(r"[({⦃]([^:()]*?):", m.group(1)):
            declared.update(g.group(1).split())
    if not any(hnames):
        i = len(binders)  # no header binders: every Lean binder is a candidate
    htext = text[hd.kw : hd.assign]
    out = []
    for b in binders[:i]:
        n = b["name"]
        if n in declared or n in hnames or "_@" in n or n.startswith("inst"):
            continue
        if ident_re(n).search(htext) and not binds_name(htext, n):
            out.append(f"{{{n} : {b['type']}}}")
    return out


def spec_name(name: str) -> str:
    """`N.x` → `N.Spec.x`."""
    comps = name.split(".")
    return ".".join(comps[:-1] + ["Spec", comps[-1]])


def theorem_index(text: str, line: int) -> int:
    """Index of the `theorem` keyword on 1-based line `line`."""
    start = sum(len(ln) + 1 for ln in text.split("\n")[: line - 1])
    k = text.find("theorem", start)
    if k < 0:
        raise ConvertError(f"no `theorem` at line {line}")
    return k


def find_theorem(text: str, t: dict) -> int:
    """Index of the `theorem` keyword of `t` in `text` (positions move after edits)."""
    short = t["name"].split(".")[-1]
    pat = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:private |protected )?theorem ([\w.'!?₀-₉]*"
                     + re.escape(short) + r")(?![\w'!?.])", re.M)
    # `theorem _root_.A.b` declares `A.b`: compare without the `_root_.` prefix.
    hits = [m for m in pat.finditer(text)
            if t["name"].endswith(m.group(1).removeprefix("_root_."))]
    if len(hits) != 1:
        raise SystemExit(f"convert_spec: {len(hits)} declarations match {t['name']}")
    return hits[0].start() + hits[0].group(0).index("theorem")


