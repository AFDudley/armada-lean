# Reachability conversion


@dataclass
class Pair:
    state: str
    hyp: str
    head: str  # head constant of the hypothesis type


@dataclass
class Conversion:
    theorem: dict
    header: Header
    pairs: list[Pair]
    calls: list[tuple] = field(default_factory=list)


def reach_type(hyp_text: str, state: str, head: str) -> tuple[str, str | None]:
    """The reachable-state type for a hypothesis `R … state`, and the native
    hypothesis type that the access line restores (None when it is
    `Machine.Reachable` itself)."""
    t = collapse(hyp_text)
    if not re.search(r"(?<![\w.'])" + re.escape(state) + r"$", t):
        raise ConvertError(f"hypothesis {t!r} does not end with the state {state}")
    pre = t[: -len(state)].rstrip()
    if head == "Machine.Reachable":
        if not pre.endswith(".Reachable"):
            raise ConvertError(f"cannot read the machine of {t!r}")
        m_text = pre[: -len(".Reachable")]
        m = re.fullmatch(r"\(Nitro\.network (.+)\)", m_text)
        if m:
            return f"Nitro.ReachableNetwork {m.group(1)}", None
        m = re.fullmatch(r"\(Nitro\.participant (.+)\)", m_text)
        if m:
            return f"Nitro.ReachableParticipant {m.group(1)}", None
        if not re.fullmatch(r"[\w.']+", m_text) and not (
            m_text.startswith("(") and m_text.endswith(")")
        ):
            m_text = f"({m_text})"
        return f"ReachableState {m_text}", None
    if head == "ArmadaLean.Nitro.Reachable":
        args = pre[len("Reachable") :].strip() if pre.startswith("Reachable") else None
        if args is None:
            raise ConvertError(f"cannot read {t!r}")
        return f"ReachableState (Nitro.chain {args})", t
    if head == "ArmadaLean.Nitro.ReachableSigned":
        if not pre.startswith("ReachableSigned"):
            raise ConvertError(f"cannot read {t!r}")
        args = pre[len("ReachableSigned") :].strip()
        return f"ReachableState (Nitro.signedChain {args})", t
    if head == "Reachable":  # the pool's own `Reachable` (`Pool.lean`)
        if pre != "Reachable":
            raise ConvertError(f"cannot read {t!r}")
        return "ReachableState Pool.machine", t
    raise ConvertError(f"no reachable-state type for the predicate {head}")


def binds_name(text: str, name: str) -> bool:
    """`True` when `text` binds `name`: the name follows a binder keyword (`∀`,
    `∃`, `λ`, `fun`), with only names and brackets between."""
    for m in ident_re(name).finditer(text):
        k = m.start() - 1
        while k >= 0 and (text[k] in " ({⦃" or re.match(r"[\w'!?₀-₉.]", text[k])):
            if text[k - 2 : k + 1] == "fun" and (k < 3 or not re.match(r"\w", text[k - 3])):
                return True
            k -= 1
        if k >= 0 and text[k] in "∀∃λ":
            return True
    return False


def convert_pair(htext: str, p: Pair) -> tuple[str, str]:
    """Convert one (state, hypothesis) pair in the header text `htext` (from
    `theorem` to just before `:=`). Edits are in place: the state group is replaced,
    the hypothesis group is deleted, and later uses of the state read `s.state`.
    Returns the new header text and the access line."""
    text = htext + ":= sorry"
    mask = code_mask(text)
    hd = parse_header(text, mask, 0)
    names = [g.names for g in hd.groups]
    si = next((k for k, ns in enumerate(names) if p.state in ns), None)
    hi = next((k for k, ns in enumerate(names) if p.hyp in ns), None)
    if si is None or hi is None:
        raise ConvertError(f"binder {p.state} or {p.hyp} not in the header")
    if names[hi] != [p.hyp]:
        raise ConvertError(f"hypothesis {p.hyp} shares a binder group")
    if hi < si:
        raise ConvertError("hypothesis before its state")
    sg, hg = hd.groups[si], hd.groups[hi]
    ty, native = reach_type(hg.type_text, p.state, p.head)
    between = [n for k in range(si + 1, hi) for n in names[k]]
    used = [n for n in between if ident_re(n).search(hg.type_text)]
    if used:
        raise ConvertError(f"{p.hyp} mentions binders after {p.state}: {used}")
    rest = text[sg.end : hg.start] + text[hg.end : hd.assign]
    if ident_re(p.hyp).search(rest):
        raise ConvertError(f"a later binder or the conclusion uses {p.hyp}")
    if binds_name(rest, p.state):
        raise ConvertError(f"a later binder or the conclusion rebinds {p.state}")
    rep = ident_re(p.state)
    # The new state group(s).
    b = sg.bracket
    close = CLOSE[OPEN.index(b)]
    pos = sg.names.index(p.state)
    before, after = sg.names[:pos], sg.names[pos + 1 :]
    parts = []
    if before:
        parts.append(f"{b}{' '.join(before)} :{sg.type_text}{close}")
    parts.append(f"({p.state} : {ty})")
    if after:
        parts.append(f"{b}{' '.join(after)} :{sg.type_text}{close}")
    # Delete the hypothesis group: the whole line when it is alone on its line,
    # else the group and the blanks before it.
    ls = text.rfind("\n", 0, hg.start) + 1
    le = text.find("\n", hg.end)
    alone_before = text[ls : hg.start].strip() == ""
    alone_after = le > 0 and text[hg.end : le].strip() == ""
    if alone_before and alone_after:
        del_s, del_e = ls, le + 1  # the whole line
    elif alone_before:
        del_s, del_e = hg.start, hg.end  # the group and the blanks after it
        while text[del_e] in " \t":
            del_e += 1
    else:
        del_s, del_e = hg.start, hg.end  # the blanks before the group and the group
        while text[del_s - 1] in " \t":
            del_s -= 1
    out = (text[: sg.start] + " ".join(parts)
           + rep.sub(p.state + ".state", text[sg.end : del_s])
           + rep.sub(p.state + ".state", text[del_e : hd.assign]))
    if native:
        access = f"obtain_reach ⟨{p.state}, {p.hyp} : {native}⟩ := {p.state}"
    else:
        access = f"obtain_reach ⟨{p.state}, {p.hyp}⟩ := {p.state}"
    return out, access


def convert_header(text: str, hd: Header, pairs: list[Pair]) -> tuple[str, list[str]]:
    """The new header text (from `theorem` to `:=`, exclusive) and the access lines."""
    htext = text[hd.kw : hd.assign]
    access = []
    for p in pairs:
        htext, a = convert_pair(htext, p)
        access.append(a)
    return htext, access


def is_sorry_body(body: str) -> bool:
    b = collapse(body)
    return b in ("sorry", "by sorry")


def repair_body(body: str, access: list[str]) -> str:
    """Insert the access lines at the start of the proof body `body` (the text
    after `:=`)."""
    if not access or is_sorry_body(body):
        return body
    m = re.match(r"[ \t]*by[ \t]*\n", body)
    if m:
        rest = body[m.end() :]
        indent = re.match(r"[ \t]*", rest).group(0)
        return body[: m.end()] + "".join(f"{indent}{a}\n" for a in access) + rest
    m = re.match(r"[ \t]*by[ \t]+", body)
    if m:
        return body[: m.end()] + "".join(f"{a}; " for a in access) + body[m.end() :]
    return " " + " ".join(f"obtain_reach% {a[len('obtain_reach '):]};" for a in access) + body


