class ConvertError(Exception):
    pass


# ---------------------------------------------------------------------------
# Header parsing


@dataclass
class Group:
    start: int  # index of the opening bracket
    end: int  # index after the closing bracket
    bracket: str
    names: list[str]
    type_text: str  # text after the top-level `:` inside the group


@dataclass
class Header:
    kw: int  # index of `theorem`
    name: str
    name_end: int
    groups: list[Group]
    colon: int  # index of the top-level `:` before the type
    assign: int  # index of the top-level `:=`
    body_end: int  # index of the end of the body (start of the next command)

    def type_text(self, text: str) -> str:
        return text[self.colon + 1 : self.assign]


def skip_ws(text: str, mask: list[bool], i: int) -> int:
    while i < len(text) and (text[i].isspace() or not mask[i]):
        i += 1
    return i


def match_close(text: str, mask: list[bool], i: int) -> int:
    """Index after the bracket that closes the one at `i`."""
    depth = 0
    while i < len(text):
        if mask[i]:
            if text[i] in OPEN:
                depth += 1
            elif text[i] in CLOSE:
                depth -= 1
                if depth == 0:
                    return i + 1
        i += 1
    raise ConvertError("unbalanced bracket")


def body_end(text: str, start: int) -> int:
    """The start of the next line at column 0 that is not blank and not a `|`
    alternative: the next command."""
    i = text.find("\n", start)
    while i >= 0:
        j = i + 1
        if j < len(text) and text[j] not in " \t\n|)]}⟩":
            return j
        i = text.find("\n", j)
    return len(text)


def parse_header(text: str, mask: list[bool], kw: int) -> Header:
    i = kw + len("theorem")
    i = skip_ws(text, mask, i)
    m = re.compile(r"[^\s(\[{⦃:]+").match(text, i)
    if not m:
        raise ConvertError("no theorem name")
    name, name_end = m.group(0), m.end()
    i = name_end
    groups: list[Group] = []
    while True:
        i = skip_ws(text, mask, i)
        if text[i] in "([{⦃":
            end = match_close(text, mask, i)
            inner = text[i + 1 : end - 1]
            inner_mask = mask[i + 1 : end - 1]
            depth = 0
            colon = -1
            for k, ch in enumerate(inner):
                if not inner_mask[k]:
                    continue
                if ch in OPEN:
                    depth += 1
                elif ch in CLOSE:
                    depth -= 1
                elif ch == ":" and depth == 0 and not inner.startswith(":=", k):
                    colon = k
                    break
            if colon < 0:
                names, ty = [], inner
            else:
                names, ty = inner[:colon].split(), inner[colon + 1 :]
            groups.append(Group(i, end, text[i], names, ty))
            i = end
        elif text[i] == ":" and not text.startswith(":=", i):
            colon = i
            break
        else:
            raise ConvertError(f"unexpected header text at {text[i:i + 40]!r}")
    depth = 0
    pending_let = 0  # a `let`/`have` in the statement owns the next top-level `:=`
    j = colon + 1
    while j < len(text):
        if mask[j]:
            ch = text[j]
            if ch in OPEN:
                depth += 1
            elif ch in CLOSE:
                depth -= 1
            elif depth == 0 and re.match(r"(?<![\w.'])(let|have)\s", text[j - 1 : j + 5] if j else ""):
                pass
            elif depth == 0 and text.startswith(":=", j):
                if pending_let:
                    pending_let -= 1
                else:
                    break
            if depth == 0 and re.match(r"(let|have)\s", text[j : j + 5]) and (
                    j == 0 or not re.match(r"[\w.']", text[j - 1])):
                pending_let += 1
        j += 1
    else:
        raise ConvertError("no `:=` after the statement")
    return Header(kw, name, name_end, groups, colon, j, body_end(text, j))


def collapse(s: str) -> str:
    """Drop `--` comments and collapse whitespace."""
    s = re.sub(r"--[^\n]*", "", s)
    return " ".join(s.split())


